package com.skala.planbmarket.domain.enums;

/**
 * 판매 등록 상태.
 *
 * 구매는 두 단계로 나뉨 — 예약금을 걸어 자리를 잡고(RESERVED), 제한시간 안에 결제해야
 * 거래가 성립함(IN_ESCROW). 중간에 예약을 취소하거나 제한시간을 넘기면 OPEN으로 돌아감.
 *
 * 왜 한 번에 사게 하지 않느냐면, 소멸성 자산이라 "살까 말까" 고민하는 동안에도 티켓이
 * 계속 소멸하기 때문임. 예약금을 걸면 그 시간만큼 판매자가 다른 구매자를 못 받는데,
 * 그 기회비용을 아무 대가 없이 판매자에게만 지우면 불공평함.
 */
public enum ListingStatus {

    /** 등록됨, 구매 대기 */
    OPEN,

    /** 예약금이 걸려 자리가 잡힘. 결제 제한시간이 돌고 있음 */
    RESERVED,

    /** 결제 완료, 에스크로 보관 중 */
    IN_ESCROW,

    /** 거래 확정 */
    COMPLETED,

    /** 판매자가 철회함 */
    WITHDRAWN,

    /** 만료로 실효됨 */
    EXPIRED
}
